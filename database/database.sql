CREATE DATABASE IF NOT EXISTS solar_totem CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE solar_totem;

CREATE TABLE users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(180) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('user','technician','administrator','executive') NOT NULL DEFAULT 'user',
  status ENUM('active','inactive','blocked') NOT NULL DEFAULT 'active',
  email_verified_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE stations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  station_code VARCHAR(30) NOT NULL UNIQUE,
  location VARCHAR(180) NOT NULL,
  status VARCHAR(30) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE charging_ports (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  station_id BIGINT UNSIGNED NOT NULL,
  port_number TINYINT UNSIGNED NOT NULL,
  port_code VARCHAR(30) NOT NULL UNIQUE,
  status VARCHAR(30) NOT NULL,
  last_seen_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (station_id) REFERENCES stations(id),
  UNIQUE KEY unique_station_port (station_id, port_number)
);

CREATE TABLE charging_sessions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NULL,
  station_id BIGINT UNSIGNED NOT NULL,
  port_id BIGINT UNSIGNED NOT NULL,
  session_code VARCHAR(40) NOT NULL UNIQUE,
  started_at DATETIME NOT NULL,
  finished_at DATETIME NULL,
  duration_seconds INT UNSIGNED NULL,
  status VARCHAR(30) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (station_id) REFERENCES stations(id),
  FOREIGN KEY (port_id) REFERENCES charging_ports(id)
);
